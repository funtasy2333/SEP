import { Mark, mergeAttributes } from '@tiptap/core'
import { Plugin, Selection } from '@tiptap/pm/state'
import { pmToIr, resolve } from '@ses/shared'
import type { Mark as PMMark, Node as PMNode } from '@tiptap/pm/model'

/** Keep formatting boundaries around unchanged prefixes/suffixes when a number gains digits. */
function remapTextBoundary(offset: number, before: string, after: string): number {
  let prefix = 0
  while (prefix < Math.min(before.length, after.length) && before[prefix] === after[prefix]) prefix++
  let suffix = 0
  while (suffix < Math.min(before.length, after.length) - prefix && before[before.length - suffix - 1] === after[after.length - suffix - 1]) suffix++
  if (offset <= prefix) return offset
  if (offset >= before.length - suffix) return after.length - (before.length - offset)
  return prefix + Math.round((offset - prefix) * (after.length - prefix - suffix) / (before.length - prefix - suffix))
}

type CrossRefCommandAttrs = (
  | { targetId: string; refId?: string | null }
  | { targetId?: null; refId: string }
) & { refType: string }

declare module '@tiptap/core' {
  interface Commands<ReturnType> {
    crossRef: {
      setCrossRef: (attrs: CrossRefCommandAttrs) => ReturnType
      unsetCrossRef: () => ReturnType
    }
  }
}

/**
 * 交叉引用标记
 * 用于引用文档内的章、条、表、图、公式、附录等
 * refType: chapter | clause | table | figure | formula | appendix | bibEntry
 *   另有 listItem（被引用的有序列项，WP8.M G4）与 abbreviation（缩略语表中的项，WP8.M G2），
 *   与 IR 的 targetKind 一一对应（见 pmToIr 的 REF_KIND_MAP）。
 */
export const CrossRef = Mark.create({
  name: 'crossRef',
  // StarterKit's generic link handler opens every anchor, including this mark.
  priority: 1100,
  inclusive: false,

  addAttributes() {
    return {
      /** 被引用元素的 id */
      refId: { default: null, parseHTML: element => element.getAttribute('refId') },
      /** 新IR契约的稳定目标ID；refId继续用于旧PM文档兼容。 */
      targetId: { default: null, parseHTML: element => element.getAttribute('targetId') },
      /** 引用类型 */
      refType: { default: 'chapter', parseHTML: element => element.getAttribute('refType') ?? 'chapter' },
      /** 显示文本（自动生成的编号文本） */
      refText: { default: null, parseHTML: element => element.getAttribute('refText') },
    }
  },

  parseHTML() {
    return [{ tag: 'a[data-type="cross-ref"]', priority: 51 }]
  },

  renderHTML({ HTMLAttributes }) {
    const targetId = HTMLAttributes.targetId ?? HTMLAttributes.refId
    return [
      'a',
      mergeAttributes(HTMLAttributes, {
        'data-type': 'cross-ref',
        class: 'std-cross-ref',
        href: targetId ? `#${targetId}` : null,
      }),
      0,
    ]
  },

  addCommands() {
    return {
      setCrossRef:
        (attrs) =>
        ({ commands }) => {
          // Keep legacy calls on refId while clearing any stale canonical value.
          // Canonical calls win if both fields are provided, including an empty targetId.
          const targetId = attrs.targetId ?? attrs.refId
          const markAttrs = attrs.targetId == null
            ? { ...attrs, targetId: null, refId: targetId }
            : { ...attrs, targetId, refId: null }
          return commands.setMark(this.name, markAttrs)
        },
      unsetCrossRef:
        () =>
        ({ commands }) => {
          return commands.unsetMark(this.name)
        },
    }
  },

  addProseMirrorPlugins() {
    return [new Plugin({
      appendTransaction(transactions, _oldState, state) {
        if (!transactions.some(tr => tr.docChanged)) return null
        const managed: Array<{ pos: number; to: number; mark: PMMark; nodes: PMNode[] }> = []
        state.doc.descendants((node, pos) => {
          const mark = node.marks.find(mark => mark.type.name === 'crossRef')
          // Only references generated by the picker are managed. Preserve custom/legacy text.
          if (!node.isText || !mark || typeof mark.attrs.refText !== 'string' || !mark.attrs.refText) return
          const previous = managed[managed.length - 1]
          if (previous?.to === pos && previous.mark.eq(mark)) { previous.to += node.nodeSize; previous.nodes.push(node) }
          else managed.push({ pos, to: pos + node.nodeSize, mark, nodes: [node] })
        })
        if (!managed.length) return null
        const labels = resolve(pmToIr(state.doc.toJSON()).doc).labels
        const tr = state.tr
        for (const { pos, to, mark, nodes } of managed.reverse()) {
          const label = labels[mark.attrs.targetId ?? mark.attrs.refId]?.refText
          if (!label || label === mark.attrs.refText) continue
          const before = nodes.map(node => node.text).join('')
          const count = before.length / mark.attrs.refText.length
          if (!Number.isInteger(count) || before !== mark.attrs.refText.repeat(count)) continue
          const after = label.repeat(count)
          let offset = 0
          const replacement: PMNode[] = []
          for (const node of nodes) {
            const from = remapTextBoundary(offset, before, after)
            offset += node.nodeSize
            const text = after.slice(from, remapTextBoundary(offset, before, after))
            const marks = node.marks.map(item => item.eq(mark) ? mark.type.create({ ...mark.attrs, refText: label }) : item)
            if (text) replacement.push(state.schema.text(text, marks))
          }
          tr.replaceWith(pos, to, replacement)
        }
        return tr.docChanged ? tr : null
      },
      props: {
        handleClick(view, _pos, event) {
          const element = event.target instanceof Element ? event.target : null
          const anchor = element?.closest('a[data-type="cross-ref"], a[data-type="term-ref"], a[data-type="bib-ref"]')
          if (!anchor || !view.dom.contains(anchor)) return false
          event.preventDefault()
          const targetId = anchor.getAttribute('targetId') ?? anchor.getAttribute('refId')
          let targetPos: number | undefined
          if (targetId) view.state.doc.descendants((node, pos) => {
            if (targetPos !== undefined) return false
            if (node.attrs.nodeId === targetId) { targetPos = pos; return false }
          })
          if (targetPos === undefined) {
            view.dom.dispatchEvent(new CustomEvent('ses:reference-missing', { bubbles: true }))
            return true
          }
          const targetNode = view.state.doc.nodeAt(targetPos)!
          const selection = Selection.near(view.state.doc.resolve(targetPos + (targetNode.isLeaf ? 0 : 1)))
          view.dispatch(view.state.tr.setSelection(selection))
          view.focus()
          const dom = view.nodeDOM(targetPos)
          if (dom instanceof HTMLElement) dom.scrollIntoView?.({ block: 'center', behavior: 'smooth' })
          return true
        },
      },
    })]
  },
})
